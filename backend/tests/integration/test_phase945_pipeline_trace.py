def test_breakout_momentum_gate_logic():
    # Price = 100, SMA_20 = 100, ATR = 2.0 -> Magnitude = 0 < 1.0 (0.5 * ATR) -> INSIGNIFICANT_MOMENTUM
    price_flat = 100.0
    sma20_flat = 100.0
    atr = 2.0

    magnitude_flat = abs(price_flat - sma20_flat)
    is_momentum_flat = magnitude_flat >= (atr * 0.5)
    assert is_momentum_flat is False # Correctly rejected

    # Price = 105, SMA_20 = 100, ATR = 2.0 -> Magnitude = 5 > 1.0 -> PASSES BREAKOUT MOMENTUM
    price_breakout = 105.0
    magnitude_breakout = abs(price_breakout - sma20_flat)
    is_momentum_breakout = magnitude_breakout >= (atr * 0.5)
    assert is_momentum_breakout is True # Passes breakout momentum gate
