    d = {}
    for sym, name in raw_companies:
        s_clean = sym.strip().upper()
        if s_clean and s_clean not in d:
            d[s_clean] = name.strip()

    res = {k: d[k] for k in list(d.keys())[:500]}
    validate_nifty500_universe(list(res.keys()))
    return res

